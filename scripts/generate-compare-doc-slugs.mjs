/**
 * Generate src/lib/compare-doc-slugs.ts from content/compare/*.md frontmatter.
 *
 * Run manually after adding/removing compare docs:
 *   node scripts/generate-compare-doc-slugs.mjs
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import matter from "gray-matter";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const contentDir = path.resolve(__dirname, "../content/compare");
const outFile = path.resolve(__dirname, "../src/lib/compare-doc-slugs.ts");

const entries = fs
  .readdirSync(contentDir, { withFileTypes: true })
  .filter((e) => e.isFile() && e.name.endsWith(".md"))
  .map((e) => {
    const filePath = path.join(contentDir, e.name);
    const raw = fs.readFileSync(filePath, "utf8");
    const { data } = matter(raw);
    const slug = data?.slug || e.name.replace(/\.md$/, "");
    return slug;
  })
  .filter(Boolean)
  .sort();

const deduped = [...new Set(entries)];

const source = `// AUTO-GENERATED by scripts/generate-compare-doc-slugs.mjs
// Do not edit by hand. Run the script after adding/removing compare docs.

export const COMPARE_DOC_SLUGS: Set<string> = new Set([
${deduped.map((s) => `  "${s}",`).join("\n")}
]);
`;

fs.writeFileSync(outFile, source, "utf8");
console.log(`Generated ${outFile} with ${deduped.length} compare doc slug(s).`);
