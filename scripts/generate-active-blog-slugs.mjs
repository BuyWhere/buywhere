/**
 * Build-time script to generate ACTIVE_BLOG_SLUGS from content/blog/*.md.
 *
 * This eliminates drift between sitemap-blog.xml (generated from content/blog)
 * and middleware's ACTIVE_BLOG_SLUGS allowlist.
 */

import fs from "node:fs";
import path from "node:path";
import matter from "gray-matter";

const blogDirectory = path.join(process.cwd(), "content/blog");
const outputFile = path.join(process.cwd(), "src/lib/active-blog-slugs.ts");

function getActiveSlugs() {
  const files = fs.readdirSync(blogDirectory).filter((file) => file.endsWith(".md"));
  const slugs = [];

  for (const file of files) {
    const fullPath = path.join(blogDirectory, file);
    const source = fs.readFileSync(fullPath, "utf8");

    if (!source.startsWith("---")) {
      continue;
    }

    try {
      const parsed = matter(source);
      const data = parsed.data;

      // Match src/lib/blog.ts: only fully-published posts are routeable and emitted in the sitemap.
      if (data.slug && data.title && data.description && data.publishedAt) {
        slugs.push(data.slug);
      }
    } catch {
      // Skip malformed files, matching getAllBlogPosts() behavior.
    }
  }

  return slugs.sort();
}

function generateOutputFile(slugs) {
  const slugArray = slugs.map((slug) => `"${slug}"`).join(",\n  ");
  const output = `/**
 * AUTO-GENERATED FILE - Do not edit manually.
 * Generated by scripts/generate-active-blog-slugs.mjs.
 *
 * Derived from content/blog/*.md at build time so middleware stays in sync
 * with sitemap-blog.xml and the blog route's generateStaticParams().
 */

export const ACTIVE_BLOG_SLUGS: string[] = [
  ${slugArray},
];
`;

  fs.writeFileSync(outputFile, output);
  console.log(`Generated ${path.relative(process.cwd(), outputFile)} with ${slugs.length} active blog slugs`);
}

const slugs = getActiveSlugs();
generateOutputFile(slugs);
