-- Catalog DB only. Do not apply to Paperclip control-plane DB.

CREATE SCHEMA IF NOT EXISTS monitoring;

CREATE TABLE IF NOT EXISTS monitoring.sweep_results (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  sweep_id text NOT NULL,
  market varchar(2) NOT NULL,
  cell_count integer NOT NULL,
  zero_result_count integer NOT NULL,
  zero_result_rate numeric(7,6) NOT NULL,
  near_miss_count integer NOT NULL,
  near_miss_rate numeric(7,6) NOT NULL,
  error_count integer NOT NULL DEFAULT 0,
  predicate_fails_reason text,
  swept_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT sweep_results_market_check CHECK (market IN ('sg', 'us', 'my', 'th', 'vn', 'id', 'ph')),
  CONSTRAINT sweep_results_rates_check CHECK (
    zero_result_rate >= 0 AND zero_result_rate <= 1
    AND near_miss_rate >= 0 AND near_miss_rate <= 1
  ),
  CONSTRAINT sweep_results_counts_check CHECK (
    cell_count >= 0
    AND zero_result_count >= 0
    AND near_miss_count >= 0
    AND error_count >= 0
  ),
  CONSTRAINT sweep_results_sweep_market_key UNIQUE (sweep_id, market)
);

CREATE INDEX IF NOT EXISTS idx_sweep_results_market_time
  ON monitoring.sweep_results (market, swept_at DESC);

CREATE INDEX IF NOT EXISTS idx_sweep_results_swept_at
  ON monitoring.sweep_results (swept_at DESC);

ALTER TABLE monitoring.alert_history
  DROP CONSTRAINT IF EXISTS alert_history_market_check;

ALTER TABLE monitoring.alert_history
  ADD CONSTRAINT alert_history_market_check
  CHECK (market::text = ANY (ARRAY['sg', 'us', 'my', 'th', 'vn', 'id', 'ph']));

CREATE OR REPLACE VIEW monitoring.v_ceo_kpis AS
WITH daily_sweeps AS (
  SELECT
    date_trunc('day', swept_at AT TIME ZONE 'UTC')::date AS day,
    AVG(near_miss_rate) AS daily_near_miss_rate
  FROM monitoring.sweep_results
  WHERE swept_at >= CURRENT_DATE - INTERVAL '7 days'
  GROUP BY 1
), seven_day AS (
  SELECT COALESCE(AVG(daily_near_miss_rate), 0::numeric) AS near_miss_rate
  FROM daily_sweeps
), latest_sweep AS (
  SELECT COALESCE(MAX(near_miss_rate), 0::numeric) AS max_near_miss_rate
  FROM monitoring.sweep_results
  WHERE sweep_id = (
    SELECT sweep_id
    FROM monitoring.sweep_results
    ORDER BY swept_at DESC
    LIMIT 1
  )
)
SELECT
  CURRENT_DATE AS report_date,
  0::numeric AS zero_result_rate,
  seven_day.near_miss_rate,
  seven_day.near_miss_rate < 0.03 AS near_miss_7day_mean_under_threshold,
  latest_sweep.max_near_miss_rate < 0.04 AS near_miss_latest_sweep_under_threshold,
  CASE
    WHEN seven_day.near_miss_rate < 0.03 AND latest_sweep.max_near_miss_rate < 0.04 THEN 'healthy'::text
    WHEN seven_day.near_miss_rate < 0.05 THEN 'warning'::text
    ELSE 'critical'::text
  END AS p1_3_nm_status,
  now() AS computed_at
FROM seven_day, latest_sweep;
